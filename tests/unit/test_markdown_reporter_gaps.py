from __future__ import annotations

from pathlib import Path

from arkhon.reporting.markdown_reporter import MarkdownReporter


def test_markdown_reporter_renders_statuses_and_unknown_values() -> None:
    report = {
        "project": "Demo",
        "report_id": "R-1",
        "commit_sha": "a" * 40,
        "generated_at": "2026-11-03T00:00:00Z",
        "apxoh_version": "1.0.0",
        "final_decision": "APPROVED",
        "sections": {
            "testing": {"status": "PASS", "evidence_ids": ["E1", "E2"]},
            "security": {"status": "FAIL", "evidence_ids": []},
            "unknown": {"status": "UNRECOGNIZED"},
        },
    }
    output = MarkdownReporter().render(report)
    assert "# Engineering Quality Report — Demo" in output
    assert "APPROVED" in output
    assert "| testing |" in output and "| 2 |" in output
    assert "UNRECOGNIZED" in output
    assert "Generated by Apxoh" in output


def test_markdown_reporter_defaults_and_write(
    tmp_path: Path, monkeypatch
) -> None:
    reporter = MarkdownReporter()
    report = {
        "project": "Demo", "report_id": "R-2", "commit_sha": "b" * 40,
        "generated_at": "now", "apxoh_version": "1.0",
    }
    monkeypatch.setattr(
        "arkhon.reporting.markdown_reporter.JsonReporter.build", lambda _self, _root: report
    )
    output = tmp_path / "reports"
    target = reporter.write(tmp_path, output)
    assert target.is_file()
    assert "PENDING_EVIDENCE" in target.read_text(encoding="utf-8")
