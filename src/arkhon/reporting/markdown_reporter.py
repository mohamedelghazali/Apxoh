"""Markdown report generator."""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Any

from arkhon.core.logging import get_logger
from arkhon.reporting.json_reporter import JsonReporter

logger = get_logger("reporting.markdown")
STATUS_EMOJI = {
    "PASS": "✅",
    "FAIL": "❌",
    "BLOCKED": "⏸",
    "NOT_APPLICABLE": "➖",
    "APPROVED": "✅",
    "REJECTED": "❌",
    "PENDING_EVIDENCE": "⏸",
}


@dataclass
class MarkdownReporter:
    """Renders a JSON report as Markdown."""

    def render(self, report: dict[str, Any]) -> str:
        lines = [
            f"# Engineering Quality Report — {report['project']}",
            "",
            f"- **Report ID:** `{report['report_id']}`",
            f"- **Commit:** `{report['commit_sha']}`",
            f"- **Generated:** {report['generated_at']}",
            f"- **Apxoh:** {report['apxoh_version']}",
        ]
        decision = report.get("final_decision", "PENDING_EVIDENCE")
        lines.extend(
            [
                f"- **Decision:** {STATUS_EMOJI.get(decision, '')} **{decision}**",
                "",
                "## Sections",
                "",
                "| Section | Status | Evidence |",
                "| :--- | :--- | :--- |",
            ]
        )
        for name, section in report.get("sections", {}).items():
            status = section.get("status", "NOT_APPLICABLE")
            count = len(section.get("evidence_ids", []))
            lines.append(f"| {name} | {STATUS_EMOJI.get(status, '')} {status} | {count} |")
        lines.extend(
            [
                "",
                "---",
                "",
                "Generated by Apxoh — Software Engineering Governance & Assurance System.",
                "",
            ]
        )
        return "\n".join(lines)

    def write(self, project_root: Path, output_dir: Path) -> Path:
        report = JsonReporter().build(project_root)
        output_dir.mkdir(parents=True, exist_ok=True)
        target = output_dir / "report.md"
        target.write_text(self.render(report), encoding="utf-8")
        return target
